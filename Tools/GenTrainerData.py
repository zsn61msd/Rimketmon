#!/usr/bin/env python3
"""PokeRogue 복원 소스에서 체육관 관장 데이터를 뽑아 Engine/Data/TrainerData.cs 를 만든다.
관장: id|이름|타입|대표 포켓몬 슬롯(종족ID,종족ID/대안;...)  — 종족 id는 PBS id로 변환(없으면 제외).
"""
import argparse, os, re, collections
ap = argparse.ArgumentParser()
ap.add_argument('--pbs', required=True); ap.add_argument('--pr', required=True); ap.add_argument('--out', required=True)
a = ap.parse_args()

def norm(s): return re.sub(r'[^A-Z0-9]', '', s.upper())
pbs_ids = {}
for fn in ('pokemon.txt', 'pokemon_base_Gen_9_Pack.txt'):
    p = os.path.join(a.pbs, fn)
    if os.path.exists(p):
        for l in open(p, encoding='utf-8-sig'):
            m = re.match(r'\[(.+)\]', l.strip())
            if m: pbs_ids.setdefault(norm(m.group(1)), m.group(1))

TYPES = ['NORMAL','FIRE','WATER','GRASS','ELECTRIC','ICE','FIGHTING','POISON','GROUND','FLYING','PSYCHIC','BUG','ROCK','GHOST','DRAGON','DARK','STEEL','FAIRY']
tc = open(os.path.join(a.pr, 'data/trainers/trainer-config.ts'), encoding='utf-8').read()
gyms = re.findall(r'\[TrainerType\.(\w+)\]: new TrainerConfig\([^)]*\)\s*\.initForGymLeader\(signatureSpecies\["(\w+)"\],\s*(true|false),\s*PokemonType\.(\w+)', tc)
sg = open(os.path.join(a.pr, 'data/balance/signature-species.ts'), encoding='utf-8').read()

# 한글 이름: 나무위키 문서/틀(포켓몬 체육관 관장 일람, 지방별 관장 틀) 기준. 시즈(MARLON)는 일본어 이름 시즈이 기반 추정.
KO = {'BROCK':'웅','MISTY':'이슬','LT_SURGE':'마티스','ERIKA':'민화','JANINE':'도희','SABRINA':'초련','BLAINE':'강연','GIOVANNI':'비주기',
      'FALKNER':'비상','BUGSY':'호일','WHITNEY':'꼭두','MORTY':'유빈','CHUCK':'사도','JASMINE':'규리','PRYCE':'류옹','CLAIR':'이향',
      'ROXANNE':'원규','BRAWLY':'철구','WATTSON':'암페어','FLANNERY':'민지','NORMAN':'종길','WINONA':'은송','TATE':'풍','LIZA':'란','JUAN':'아단',
      'ROARK':'강석','GARDENIA':'유채','MAYLENE':'멜리사','CRASHER_WAKE':'자두','FANTINA':'맥실러','BYRON':'동관','CANDICE':'무청','VOLKNER':'전진',
      'CILAN':'덴트','CHILI':'팟','CRESS':'콘','CHEREN':'체렌','LENORA':'알로에','ROXIE':'보미카','BURGH':'아티','ELESA':'카밀레','CLAY':'야콘',
      'SKYLA':'풍란','BRYCEN':'담죽','DRAYDEN':'사간','MARLON':'시즈',
      'VIOLA':'비올라','GRANT':'자크로','KORRINA':'코르니','RAMOS':'후쿠지','CLEMONT':'시트론','VALERIE':'마슈','OLYMPIA':'고지카','WULFRIC':'우르프',
      'MILO':'아킬','KABU':'순무','OPAL':'포플러','BEDE':'비트','GORDIE':'마쿠와','MELONY':'멜론','PIERS':'두송',
      'KATY':'단풍','BRASSIUS':'콜사','IONO':'모야모','KOFU':'곤포','RYME':'라임','TULIP':'리파','GRUSHA':'그루샤'}

def slots(key):
    m = re.search(r'\b' + key + r':\s*\[(.*?)\],?\s*(?://.*)?\n', sg)
    if not m: return []
    body = m.group(1)
    out = []
    for part in re.findall(r'\[([^\]]*)\]|SpeciesId\.(\w+)', body):
        if part[0]:
            ids = [pbs_ids.get(norm(x)) for x in re.findall(r'SpeciesId\.(\w+)', part[0])]
            ids = [i for i in ids if i]
            if ids: out.append('/'.join(ids))
        elif part[1]:
            i = pbs_ids.get(norm(part[1]))
            if i: out.append(i)
    return out

rows = []
# 첫 관장(BROCK)은 정규식 앞부분 형식이 달라 별도 처리
seen = set()
first = re.search(r'\[TrainerType\.BROCK\]: new TrainerConfig\(\(t = TrainerType\.BROCK\)\)\s*\.initForGymLeader\(signatureSpecies\["BROCK"\],\s*(true|false),\s*PokemonType\.(\w+)', tc)
cand = [('BROCK', 'BROCK', first.group(1), first.group(2))] + gyms
for tt, key, male, ty in cand:
    if key in seen: continue
    seen.add(key)
    sl = slots(key)
    if not sl: continue
    name = KO.get(key, key.replace('_', ' ').title())
    rows.append('|'.join([key, name, str(TYPES.index(ty)), male, ';'.join(sl)]))

with open(a.out, 'w', encoding='utf-8') as o:
    o.write('// <auto-generated> Tools/GenTrainerData.py 가 만든 파일입니다. 직접 고치지 마세요. </auto-generated>\n')
    o.write('namespace Rimketmon.Engine\n{\n    public static partial class GameData\n    {\n')
    o.write('        /// <summary>id|이름|전문 타입|남성(true/false)|대표 포켓몬 슬롯(;구분, 대안은 /)</summary>\n')
    o.write('        public static readonly string[] GymLeaderRows =\n        {\n')
    for r in rows: o.write('            "%s",\n' % r.replace('"', '\\"'))
    o.write('        };\n    }\n}\n')
print('leaders', len(rows))
