#!/usr/bin/env python3
"""
레퍼런스 moves.txt에서 '단순 위력기'의 수치(속성/분류/위력/명중/PP)만 뽑아 Engine/Data/MoveTable.cs 를 생성한다.
기술 이름과 설명은 출력하지 않는다(공식 이름이 모드에 들어가지 않도록). 이름은 엔진이 자체 규칙으로 만든다.

사용법:  python3 -I GenMoveTable.py <moves.txt 경로> <출력 MoveTable.cs 경로>

포함 기준 (변화기/회복기/상태이상 기술은 제외 — 추후 논의):
  - 분류 Physical/Special, 위력 40 이상, 18개 속성, 단일 대상(Target = NearOther 또는 Other)
  - FunctionCode 가 None 이거나, '부가 효과만 붙은' 코드(화상/마비/독/풀죽음/능력치 변동 확률 등)
    → 부가 효과는 전부 제거하고 순수 위력기로 취급한다.
  - 제외: 반동, 2턴 소요, 연속 공격, 흡수, 위력 가변, 고정 피해, 교체, 아이템 관련, 자기 능력 하락 등
    (위력 자체를 보정하는 효과라 단순 위력으로 환산할 수 없음)
"""
import re, sys, collections

TYPES = "NORMAL FIRE WATER GRASS ELECTRIC ICE FIGHTING POISON GROUND FLYING PSYCHIC BUG ROCK GHOST DRAGON DARK STEEL FAIRY".split()
SIDE_EFFECT_ONLY = set("""
FlinchTarget BurnTarget ParalyzeTarget PoisonTarget FreezeTarget ConfuseTarget BadPoisonTarget
LowerTargetSpDef1 LowerTargetDefense1 LowerTargetAccuracy1 LowerTargetSpeed1 LowerTargetSpAtk1 LowerTargetAttack1 LowerTargetSpDef2
RaiseUserMainStats1 RaiseUserAttack1 RaiseUserSpAtk1 RaiseUserSpeed1 RaiseUserDefense1
BurnFlinchTarget FreezeFlinchTarget ParalyzeFlinchTarget ParalyzeBurnOrFreezeTarget
""".split())
MIN_POWER = 40

def parse(path):
    txt = open(path, encoding="utf-8-sig").read()
    for sec in re.split(r"\n#-+\n", txt):
        m = re.search(r"^\[([^\]]+)\]", sec, re.M)
        if not m: continue
        d = {}
        for line in sec.splitlines():
            if " = " in line and not line.startswith("["):
                k, v = line.split(" = ", 1); d[k.strip()] = v.strip()
        yield d

def main():
    src, dst = sys.argv[1], sys.argv[2]
    rows = []
    for d in parse(src):
        if d.get("Category") not in ("Physical", "Special"): continue
        if d.get("Type") not in TYPES: continue
        if d.get("Target") not in ("NearOther", "Other"): continue
        power = int(d.get("Power", "0"))
        if power < MIN_POWER: continue
        fc = d.get("FunctionCode", "")
        if fc != "None" and fc not in SIDE_EFFECT_ONLY: continue
        acc = int(d.get("Accuracy", "0")); acc = 100 if acc <= 0 else acc
        pp = int(d.get("TotalPP", "10"))
        rows.append((TYPES.index(d["Type"]), 0 if d["Category"] == "Physical" else 1, power, acc, pp))
    rows.sort()
    by_type = collections.Counter(r[0] for r in rows)

    out = []
    out.append("// <auto-generated> Tools/GenMoveTable.py 로 생성됨. 직접 수정하지 말고 생성기를 고치세요. </auto-generated>")
    out.append("// 행 형식: 속성(ElementType 번호), 분류(0 물리 / 1 특수), 위력, 명중, PP. 기술 이름은 포함하지 않는다.")
    out.append(f"// 총 {len(rows)}개 (부가 효과를 제거한 순수 위력기)")
    out.append("namespace Rimketmon.Engine")
    out.append("{")
    out.append("    internal static class MoveTable")
    out.append("    {")
    out.append("        internal static readonly int[,] Rows = new int[,]")
    out.append("        {")
    for r in rows:
        out.append("            { %d, %d, %d, %d, %d }," % r)
    out.append("        };")
    out.append("    }")
    out.append("}")
    open(dst, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"생성 완료: {len(rows)}개 -> {dst}")
    print("속성별 개수:", {TYPES[i]: by_type[i] for i in range(18)})

main()
