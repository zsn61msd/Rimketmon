#!/usr/bin/env python3
"""PBS pokemon.txt(+Gen9 base) GenderRatio → Engine/Data/GenderData.cs
usage: GenGenderData.py PBS_DIR OUT.cs"""
import sys, re, os
pbs, out = sys.argv[1:3]
R = {'AlwaysMale': 0, 'AlwaysFemale': 100, 'Female25Percent': 25, 'Female50Percent': 50, 'Female75Percent': 75,
     'FemaleOneEighth': 12.5, 'FemaleSevenEighths': 87.5, 'Genderless': -1}

# 실제 포켓몬만: 지금 Engine/Data/GameData.cs의 종족 목록에 있는 id만 남긴다(참고 게임에만 있는 몬스터 제외)
def _known_species():
    gd = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'Engine', 'Data', 'GameData.cs')
    s = open(gd, encoding='utf-8').read(); s = s[s.index('SpeciesRows'):]; s = s[:s.index('};')]
    return set(re.findall(r'"([A-Za-z0-9_]+)\|', s))
KNOWN = _known_species()
ratio = {}
for fn in ('pokemon.txt', 'pokemon_base_Gen_9_Pack.txt'):
    p = os.path.join(pbs, fn)
    if not os.path.exists(p): continue
    cur = None
    for line in open(p, encoding='utf-8'):
        m = re.match(r'\[(\w+)\]', line)
        if m: cur = m.group(1); continue
        if cur and line.startswith('GenderRatio') and '=' in line:
            v = line.split('=', 1)[1].strip()
            if v in R: ratio[cur] = R[v]
with open(out, 'w', encoding='utf-8') as o:
    o.write('// <auto-generated> Tools/GenGenderData.py\nusing System.Collections.Generic;\nnamespace Rimketmon.Engine {\npublic static partial class GenderData {\n')
    o.write('  /// <summary>종족 id → 암컷 비율(%). -1은 무성.</summary>\n  public static readonly Dictionary<string, double> FemalePercent = new Dictionary<string, double> {\n')
    for k in sorted(ratio):
        if k not in KNOWN: continue
        o.write('    {"%s", %s},\n' % (k, repr(float(ratio[k]))))
    o.write('  };\n}\n}\n')
print(len(ratio), 'species ratios')
