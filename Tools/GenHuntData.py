#!/usr/bin/env python3
"""포켓몬 사냥(바이옴)용 데이터: PokeRogue 바이옴 등장표와 포획률 → Engine/Data/HuntData.cs
바이옴 행: 키|한글 이름|아레나 그림|등급(0 흔함 1 보통 2 드묾 3 아주 드묾 4 극히 드묾)|시간(DAWN/DAY/DUSK/NIGHT/ALL)|종족;…
포획률 행: 종족 id|포획률(0~255)
"""
import re, sys, os, glob
src, gd_path, out = sys.argv[1], sys.argv[2], sys.argv[3]
gd = open(gd_path, encoding='utf-8').read()
ids = set(re.findall(r'^\s*"([A-Za-z0-9_]+)\|', gd[gd.find('SpeciesRows'):gd.find('};', gd.find('SpeciesRows'))], re.M))
fd = os.path.join(os.path.dirname(gd_path), 'FormData.cs')      # 지역폼도 등장표에 넣는다
if os.path.exists(fd):
    t = open(fd, encoding='utf-8').read(); ids |= set(re.findall(r'^\s*"([A-Z0-9_]+)\|', t[t.find('FormSpeciesRows'):t.find('FormBaseRows')], re.M))
def norm(s): return re.sub(r'[^A-Z0-9]', '', s.upper())
byn = {norm(i): i for i in ids}
for a, b in (('NIDORANF', 'NIDORANfE'), ('NIDORANM', 'NIDORANmA')):
    if b in ids: byn[a] = b
KO = {'plains':'평야','grass':'풀숲','tall-grass':'높은 풀숲','metropolis':'대도시','forest':'숲','sea':'바다','swamp':'늪','beach':'해변',
      'lake':'호수','seabed':'해저','mountain':'산','badlands':'황무지','cave':'동굴','desert':'사막','ice-cave':'얼음 동굴','meadow':'꽃밭',
      'power-plant':'발전소','volcano':'화산','graveyard':'묘지','dojo':'도장','factory':'공장','ruins':'고대 유적','wasteland':'황야',
      'abyss':'심연','space':'우주','construction-site':'공사장','jungle':'정글','fairy-cave':'요정 동굴','temple':'사원','slum':'슬럼',
      'snowy-forest':'눈 덮인 숲','island':'섬','laboratory':'연구소'}
TIERS = ['COMMON', 'UNCOMMON', 'RARE', 'SUPER_RARE', 'ULTRA_RARE']
rows = []
for f in sorted(glob.glob(os.path.join(src, 'data/balance/biomes/*.ts'))):
    key = os.path.basename(f)[:-3]
    if key not in KO: continue
    t = open(f, encoding='utf-8').read()
    pool = t[t.find('const pokemonPool'):]
    pool = pool[:pool.find('\n};')]
    for ti, tier in enumerate(TIERS):
        m = re.search(r'\[BiomePoolTier\.' + tier + r'\]:\s*\{(.*?)\n  \},', pool, re.S)
        if not m: continue
        for tm in re.finditer(r'\[TimeOfDay\.(\w+)\]:\s*\[(.*?)\]', m.group(1), re.S):
            sp = [byn.get(norm(x)) for x in re.findall(r'SpeciesId\.(\w+)', tm.group(2))]
            sp = list(dict.fromkeys(x for x in sp if x))
            if sp: rows.append('%s|%s|%s|%d|%s|%s' % (key, KO[key], key.replace('-', '_'), ti, tm.group(1), ';'.join(sp)))
rates = {}
for f in glob.glob(os.path.join(src, 'data/balance/species/*.ts')):
    t = open(f, encoding='utf-8').read()
    for m in re.finditer(r'id:\s*SpeciesId\.(\w+),.*?catchRate:\s*(\d+)', t, re.S):
        i = byn.get(norm(m.group(1)))
        if i and i not in rates: rates[i] = int(m.group(2))
with open(out, 'w', encoding='utf-8') as o:
    o.write('// <auto-generated> Tools/GenHuntData.py 가 만든 파일입니다. 직접 고치지 마세요. </auto-generated>\nnamespace Rimketmon.Engine\n{\n    public static partial class GameData\n    {\n')
    o.write('        /// <summary>바이옴 키|이름|아레나|등급|시간|종족;…</summary>\n        public static readonly string[] HuntRows =\n        {\n')
    for r in rows: o.write('            "%s",\n' % r)
    o.write('        };\n        /// <summary>종족|포획률</summary>\n        public static readonly string[] CatchRateRows =\n        {\n')
    for k in sorted(rates): o.write('            "%s|%d",\n' % (k, rates[k]))
    o.write('        };\n    }\n}\n')
print(len(rows), 'rows', len(set(r.split('|')[0] for r in rows)), 'biomes', len(rates), 'rates', 'missing rates', len(ids - set(rates)))
