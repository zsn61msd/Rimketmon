#!/usr/bin/env python3
"""도감 데이터: PokeAPI CSV(한국어, language_id 3) → Engine/Data/DexData.cs
행: 종족 id|전국도감 번호|분류(한국어)|키(m)|몸무게(kg)|설명(한국어, 가장 최근 버전)"""
import csv, re, sys, os
csvdir, gd_path, out = sys.argv[1], sys.argv[2], sys.argv[3]
gd = open(gd_path, encoding='utf-8').read()
ids = re.findall(r'^\s*"([A-Z0-9_]+)\|', gd[gd.find('SpeciesRows'):], re.M)
def norm(s): return re.sub(r'[^A-Z0-9]', '', s.upper())
species = {}
for r in csv.DictReader(open(os.path.join(csvdir, 'pokemon_species.csv'), encoding='utf-8')):
    species[norm(r['identifier'])] = int(r['id'])
species['NIDORANFE'] = 29; species['NIDORANMA'] = 32
genus = {}
for r in csv.DictReader(open(os.path.join(csvdir, 'pokemon_species_names.csv'), encoding='utf-8')):
    if r['local_language_id'] == '3': genus[int(r['pokemon_species_id'])] = r['genus']
hw = {}
for r in csv.DictReader(open(os.path.join(csvdir, 'pokemon.csv'), encoding='utf-8')):
    if r['is_default'] == '1': hw[int(r['species_id'])] = (int(r['height']) / 10.0, int(r['weight']) / 10.0)
flav = {}; flav_en = {}
for r in csv.DictReader(open(os.path.join(csvdir, 'pokemon_species_flavor_text.csv'), encoding='utf-8')):
    d = flav if r['language_id'] == '3' else flav_en if r['language_id'] == '9' else None
    if d is None: continue
    sid, ver = int(r['species_id']), int(r['version_id'])
    if sid not in d or ver > d[sid][0]: d[sid] = (ver, re.sub(r'\s+', ' ', r['flavor_text']).strip())
for k, v in flav_en.items():      # 한국어 설명이 아직 없는 종(주로 9세대)은 영어 설명
    flav.setdefault(k, v)
rows = []
for i in ids:
    n = species.get(norm(i))
    if not n: continue
    h, w = hw.get(n, (0, 0))
    t = flav.get(n, (0, ''))[1].replace('|', ' ').replace('"', "'")
    rows.append('%s|%d|%s|%g|%g|%s' % (i, n, genus.get(n, ''), h, w, t))
with open(out, 'w', encoding='utf-8') as o:
    o.write('// <auto-generated> Tools/GenDexData.py 가 만든 파일입니다(PokeAPI 데이터). 직접 고치지 마세요. </auto-generated>\nnamespace Rimketmon.Engine\n{\n    public static partial class GameData\n    {\n')
    o.write('        /// <summary>종족 id|전국도감 번호|분류|키(m)|몸무게(kg)|설명</summary>\n        public static readonly string[] DexRows =\n        {\n')
    for r in rows: o.write('            "%s",\n' % r.replace('\\', ''))
    o.write('        };\n    }\n}\n')
print(len(rows), 'of', len(ids), 'with text', sum(1 for r in rows if not r.endswith('|')))
