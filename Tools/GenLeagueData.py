#!/usr/bin/env python3
"""PokeRogue 소스(trainer-config.ts)에서 사천왕·챔피언의 파티 슬롯을 뽑아 Engine/Data/LeagueData.cs 를 만든다.
행: id|한글 이름|전문 타입(없으면 -1)|남성|슬롯(;구분, 대안은 /). 종족 id는 림켓몬 종족 목록(GameData.SpeciesRows)에 있는 것만.
한글 이름 중 일부(블루베리 학원 사천왕 등)는 일본어 이름을 옮긴 추정이다."""
import re, sys, os
tc = open(sys.argv[1], encoding='utf-8').read()
gd = open(sys.argv[2], encoding='utf-8').read()
out = sys.argv[3]
ids = set(re.findall(r'^\s*"([A-Z0-9_]+)\|', gd[gd.find('SpeciesRows'):], re.M))
def norm(s): return re.sub(r'[^A-Z0-9]', '', s.upper())
byn = {norm(i): i for i in ids}
TYPES = ['NORMAL','FIRE','WATER','GRASS','ELECTRIC','ICE','FIGHTING','POISON','GROUND','FLYING','PSYCHIC','BUG','ROCK','GHOST','DRAGON','DARK','STEEL','FAIRY']
KO = {'LORELEI':'칸나','BRUNO':'시바','AGATHA':'국화','LANCE':'목호','WILL':'일목','KOGA':'독수','KAREN':'카렌','SIDNEY':'혁진','PHOEBE':'회연',
      'GLACIA':'미혜','DRAKE':'권수','AARON':'충호','BERTHA':'들국화','FLINT':'대엽','LUCIAN':'오엽','SHAUNTAL':'망초','MARSHAL':'연무',
      'GRIMSLEY':'블래리','CAITLIN':'카틀레야','MALVA':'파키라','SIEBOLD':'즈미','WIKSTROM':'간피','DRASNA':'드라세나','HALA':'할라',
      'MOLAYNE':'멀레인','OLIVIA':'라이치','ACEROLA':'아세로라','KAHILI':'카일리','MARNIE_ELITE':'마리','BEDE_ELITE':'비트','NESSA_ELITE':'야청',
      'BEA_ELITE':'채두','ALLISTER_ELITE':'어니언','RAIHAN_ELITE':'금랑','RIKA':'칠리','POPPY':'뽀삐','LARRY_ELITE':'시유','HASSEL':'하솔',
      'CRISPIN':'아카마츠','AMARYS':'네리네','LACEY':'타로','DRAYTON':'카키츠바타',
      'BLUE':'그린','RED':'레드','LANCE_CHAMPION':'목호','STEVEN':'성호','WALLACE':'윤진','CYNTHIA':'난천','ALDER':'노간주','IRIS':'아이리스',
      'DIANTHA':'카르네','KUKUI':'쿠쿠이','HAU':'하우','LEON':'단델','MUSTARD':'마스타드','GEETA':'테사','NEMONA':'네모','KIERAN':'카지'}
blocks = re.split(r'\n\s*\[TrainerType\.', tc)
elite, champ = [], []
for b in blocks:
    m = re.match(r'(\w+)\]: new TrainerConfig', b)
    if not m: continue
    key = m.group(1)
    e = re.search(r'\.initForEliteFour\(signatureSpecies\["\w+"\],\s*(true|false),\s*PokemonType\.(\w+)', b)
    c = re.search(r'\.initForChampion\((true|false)\)', b)
    if not e and not c: continue
    slots = {}
    for pm in re.finditer(r'\.setPartyMemberFunc\(\s*(\d+),\s*getRandomPartyMemberFunc\(\s*\[([^\]]*)\]', b):
        sp = [byn.get(norm(x)) for x in re.findall(r'SpeciesId\.(\w+)', pm.group(2))]
        sp = [x for x in sp if x]
        if sp: slots[int(pm.group(1))] = '/'.join(dict.fromkeys(sp))
    sl = ';'.join(slots[k] for k in sorted(slots))
    if not sl: continue
    name = KO.get(key, key.replace('_', ' ').title())
    if e: elite.append('%s|%s|%d|%s|%s' % (key, name, TYPES.index(e.group(2)), e.group(1), sl))
    else: champ.append('%s|%s|-1|%s|%s' % (key, name, c.group(1), sl))
with open(out, 'w', encoding='utf-8') as f:
    f.write('// <auto-generated> Tools/GenLeagueData.py 가 만든 파일입니다. 직접 고치지 마세요. </auto-generated>\nnamespace Rimketmon.Engine\n{\n    public static partial class GameData\n    {\n')
    for nm, rows in (('EliteFourRows', elite), ('ChampionRows', champ)):
        f.write('        /// <summary>id|이름|전문 타입(-1 없음)|남성|파티 슬롯(;구분, 대안은 /)</summary>\n        public static readonly string[] %s =\n        {\n' % nm)
        for r in rows: f.write('            "%s",\n' % r)
        f.write('        };\n')
    f.write('    }\n}\n')
print(len(elite), len(champ))
