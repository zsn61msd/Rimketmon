#!/usr/bin/env python3
"""PokeRogue locales/ko 전투 메시지 → Engine/Data/MsgData.cs (키\t템플릿). 사용: GenMsgData.py <locales/ko> <out.cs>"""
import json, os, sys
src, out = sys.argv[1], sys.argv[2]
FILES = ['battle', 'move-trigger', 'ability-trigger', 'battler-tags', 'status-effect', 'weather', 'terrain', 'arena-tag', 'battle-info', 'fight-ui-handler', 'command-ui-handler', 'party-ui-handler', 'pokemon-summary', 'nature']
rows = []
def walk(x, p):
    if isinstance(x, dict):
        for k, v in x.items(): yield from walk(v, p + '.' + k)
    elif isinstance(x, str): yield p, x
for f in FILES:
    d = json.load(open(os.path.join(src, f + '.json'), encoding='utf-8'))
    for k, v in walk(d, f): rows.append(k + '\t' + v.replace('\n', ' ').replace('\t', ' '))
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
with open(out, 'w', encoding='utf-8') as o:
    o.write('// <auto-generated> Tools/GenMsgData.py 가 만든 파일입니다. 직접 고치지 마세요. </auto-generated>\nnamespace Rimketmon.Engine\n{\n    public static class MsgData\n    {\n        public static readonly string[] Rows =\n        {\n')
    for r in rows: o.write('            %s,\n' % q(r))
    o.write('        };\n    }\n}\n')
print(len(rows), 'rows')
