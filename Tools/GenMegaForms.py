#!/usr/bin/env python3
"""메가진화·원시회귀·거다이맥스 폼 데이터: Pokémon Showdown data/pokedex.ts에서 정식 종족값·타입·특성·무게를 읽어
Engine/Data/MegaFormData.cs 를 만든다. 배우는 기술은 원래 종족 것을 그대로 쓴다.
사용: GenMegaForms.py <showdown pokedex.ts> <Engine/Data/GameData.cs> <Engine/Data/FormData.cs> <출력 cs> <species.txt(영문 이름, 덧붙임)>"""
import re, sys
dex_path, gd_path, fd_path, out_path, sp_txt = sys.argv[1:6]
assets = sys.argv[6] if len(sys.argv) > 6 else None      # 주면: 그림(앞모습)이 없는 폼은 뺀다
import os
SPRITE_FIX = {"892-gigantamax": "892-gigantamax-single"}      # 포켓로그 그림 이름이 다른 폼
dex = open(dex_path, encoding='utf-8').read()
gd = open(gd_path, encoding='utf-8').read() + open(fd_path, encoding='utf-8').read()
def section(src, name):
    s = src[src.find(name + ' ='):]; return s[:s.find('};')]
rows = {}
for sec in ('SpeciesRows', 'FormSpeciesRows'):
    for r in re.findall(r'"([A-Z0-9_]+\|[^"]*)"', section(gd, sec)): rows[r.split('|')[0]] = r.split('|')
abil = set(re.findall(r'"([A-Z0-9]+)\|', section(gd, 'AbilityRows')))
def norm(s): return re.sub(r'[^A-Z0-9]', '', s.upper())
byn = {norm(k): k for k in rows}
TYPES = ['Normal','Fire','Water','Grass','Electric','Ice','Fighting','Poison','Ground','Flying','Psychic','Bug','Rock','Ghost','Dragon','Dark','Steel','Fairy']
ent = re.findall(r'\n\t([a-z0-9]+): \{(.*?)\n\t\},', dex, re.S)
out = []; base_rows = []; en = []; missing_ab = set(); skipped = []
for key, body in ent:
    m = re.search(r'forme: "([^"]+)"', body)
    if not m: continue
    forme = m.group(1)
    kind = 'MEGA' if forme.startswith('Mega') else 'PRIMAL' if forme == 'Primal' else 'GMAX' if forme == 'Gmax' else None
    if not kind: continue
    if re.search(r'isNonstandard: "(CAP|Custom|LGPE)"', body): continue
    base = re.search(r'baseSpecies: "([^"]+)"', body).group(1)
    bid = byn.get(norm(base))
    if not bid: skipped.append(key + ' (원래 종족 없음)'); continue
    b = rows[bid]
    name = re.search(r'name: "([^"]+)"', body).group(1)
    types = re.findall(r'"(\w+)"', re.search(r'types: \[([^\]]*)\]', body).group(1))
    st = dict(re.findall(r'(\w+): (\d+)', re.search(r'baseStats: \{([^}]*)\}', body).group(1)))
    abs_ = [norm(x) for x in re.findall(r'"([^"]+)"', re.search(r'abilities: \{([^}]*)\}', body).group(1))]
    for a in abs_:
        if a not in abil: missing_ab.add(a)
    abs_ = [a for a in abs_ if a in abil] or b[12].split(';')
    wkg = re.search(r'weightkg: ([\d.]+)', body); wkg = float(wkg.group(1)) if wkg else 0
    if wkg == 0: wkg = float(b[14]) if len(b) > 14 and b[14] else 0
    suffix = forme[len('Mega'):].lstrip('-') if kind == 'MEGA' else ''
    fid = kind + '_' + bid + (('_' + suffix.upper()) if suffix else '')
    ko = {'MEGA': '메가' + b[1] + suffix, 'PRIMAL': '원시' + b[1], 'GMAX': '거다이맥스 ' + b[1]}[kind]
    t1 = TYPES.index(types[0]); t2 = TYPES.index(types[1]) if len(types) > 1 else -1
    out.append('|'.join([fid, ko, str(t1), str(t2), st['hp'], st['atk'], st['def'], st['spa'], st['spd'], st['spe'], '0', b[11], ';'.join(abs_), '', ('%g' % wkg)]))
    spr = '%d-%s' % (int(re.search(r'num: (\d+)', body).group(1)), {'MEGA': 'mega' + ('-' + suffix.lower() if suffix else ''), 'PRIMAL': 'primal', 'GMAX': 'gigantamax'}[kind])
    spr = SPRITE_FIX.get(spr, spr)
    if assets and not os.path.exists(os.path.join(assets, spr + '.png')): skipped.append(key + ' (그림 없음)'); out.pop(); continue
    base_rows.append('|'.join([fid, bid, kind, spr]))
    en.append((norm(fid).lower(), name.replace('-Mega-', ' Mega ').replace('-Mega', ' (Mega)') if False else {'MEGA': 'Mega ' + base + (' ' + suffix if suffix else ''), 'PRIMAL': 'Primal ' + base, 'GMAX': 'Gigantamax ' + base}[kind]))
with open(out_path, 'w', encoding='utf-8') as o:
    o.write('// <auto-generated> Tools/GenMegaForms.py 가 Pokémon Showdown data/pokedex.ts 로 만든 파일입니다. 직접 고치지 마세요. </auto-generated>\nnamespace Rimketmon.Engine\n{\n    public static partial class GameData\n    {\n')
    o.write('        /// <summary>메가·원시·거다이맥스 종족(SpeciesRows와 같은 형식). 플레이어만 NPC를 통해 바꿀 수 있다.</summary>\n        public static readonly string[] MegaSpeciesRows =\n        {\n')
    for r in out: o.write('            "%s",\n' % r)
    o.write('        };\n        /// <summary>폼 id|원래 종족 id|종류(MEGA/PRIMAL/GMAX)|그림 키(포켓로그)</summary>\n        public static readonly string[] MegaBaseRows =\n        {\n')
    for r in base_rows: o.write('            "%s",\n' % r)
    o.write('        };\n    }\n}\n')
txt = open(sp_txt, encoding='utf-8').read()
have = set(l.split('\t')[0] for l in txt.split('\n') if '\t' in l)
add = ''.join('%s\t%s\n' % (k, v) for k, v in en if k not in have)
if add:
    if not txt.endswith('\n'): txt += '\n'
    open(sp_txt, 'w', encoding='utf-8').write(txt + add)
kinds = {}
for r in base_rows: k = r.split('|')[2]; kinds[k] = kinds.get(k, 0) + 1
print('폼', len(out), kinds, '| 없는 특성(원래 종족 특성으로 대체):', sorted(missing_ab), '| 건너뜀:', skipped)
