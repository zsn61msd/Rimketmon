#!/usr/bin/env python3
"""PBS items.txt(+Gen9 pack) + 한글 메시지 → Engine/Data/ItemData.cs
usage: GenItemData.py PBS_DIR <PokeAPI CSV 폴더 | item_ko.json> OUT.cs"""
import sys, json, re, os
pbs, kojson, out = sys.argv[1:4]
if os.path.isdir(kojson):      # PokeAPI CSV 폴더(github.com/PokeAPI/pokeapi data/v2/csv): 영어 이름 → 한국어 이름·설명
    import csv
    rd = lambda n: list(csv.DictReader(open(os.path.join(kojson, n + '.csv'), encoding='utf-8')))
    en = {r['item_id']: r['name'] for r in rd('item_names') if r['local_language_id'] == '9'}
    kn = {r['item_id']: r['name'] for r in rd('item_names') if r['local_language_id'] == '3'}
    kd = {}
    for r in rd('item_flavor_text'):
        if r['language_id'] == '3': kd[r['item_id']] = r['flavor_text'].replace('\n', ' ').replace('\f', ' ')
    norm = lambda x: re.sub(r'[^a-z0-9]', '', x.lower())
    ko = {'names': {}, 'descs': {}, 'byname_desc': {}}
    for i, e in en.items():
        if i in kn: ko['names'][norm(e)] = kn[i]
        if i in kd: ko['byname_desc'][norm(e)] = kd[i]
else:
    ko = json.load(open(kojson, encoding='utf-8')); ko['byname_desc'] = {}
    norm = lambda x: x
items = []
for fn in ('items.txt', 'items_Gen_9_Pack.txt'):
    p = os.path.join(pbs, fn)
    if not os.path.exists(p): continue
    cur = None
    for line in open(p, encoding='utf-8'):
        line = line.rstrip('\n')
        if line.startswith('#') or not line.strip(): continue
        m = re.match(r'\[(\w+)\]', line)
        if m:
            cur = {'id': m.group(1)}; items.append(cur); continue
        if cur is None or '=' not in line: continue
        k, v = [s.strip() for s in line.split('=', 1)]
        cur[k] = v
def esc(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
rows = []
seen = set()
for it in items:
    if it['id'] in seen: continue
    seen.add(it['id'])
    pocket = int(it.get('Pocket', '0') or 0)
    flags = [f.strip() for f in it.get('Flags', '').split(',') if f.strip()]
    if 'KeyItem' in flags or 'MegaStone' in flags and False: pass
    fling = 0; ngT = ''; ngP = 0
    for f in flags:
        m = re.match(r'Fling_(\d+)$', f)
        if m: fling = int(m.group(1))
        m = re.match(r'NaturalGift_([A-Z]+)_(\d+)', f)
        if m: ngT, ngP = m.group(1), int(m.group(2))
    en = it.get('Name', it['id'])
    kn = ko['names'].get(norm(en), '')
    desc_en = it.get('Description', '')
    desc_ko = ko['byname_desc'].get(norm(en)) or ko['descs'].get(desc_en, '')
    isb = 'Berry' in flags
    rows.append((it['id'], en, kn, pocket, int(it.get('Price', '0') or 0), fling, ngT, ngP, isb,
                 ','.join(flags), desc_en, desc_ko))
with open(out, 'w', encoding='utf-8') as o:
    o.write('// <auto-generated> Tools/GenItemData.py\nusing System.Collections.Generic;\nnamespace Rimketmon.Engine {\npublic static partial class ItemData {\n')
    o.write('  public static readonly object[][] Raw = new object[][] {\n')
    for r in rows:
        o.write('    new object[]{%s,%s,%s,%d,%d,%d,%s,%d,%s,%s,%s,%s},\n' % (
            esc(r[0]), esc(r[1]), esc(r[2]), r[3], r[4], r[5], esc(r[6]), r[7], 'true' if r[8] else 'false', esc(r[9]), esc(r[10]), esc(r[11])))
    o.write('  };\n}\n}\n')
# 진화 가능한 종족(진화의휘석 판정용)

# 실제 포켓몬만: 지금 Engine/Data/GameData.cs의 종족 목록에 있는 id만 남긴다(참고 게임에만 있는 몬스터 제외)
def _known_species():
    gd = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'Engine', 'Data', 'GameData.cs')
    s = open(gd, encoding='utf-8').read(); s = s[s.index('SpeciesRows'):]; s = s[:s.index('};')]
    return set(re.findall(r'"([A-Za-z0-9_]+)\|', s))
KNOWN = _known_species()
evo=set()
for fn in ('pokemon.txt','pokemon_base_Gen_9_Pack.txt','pokemon_forms.txt','pokemon_forms_Gen_9_Pack.txt'):
    p2=os.path.join(pbs,fn)
    if not os.path.exists(p2): continue
    cur=None
    for line in open(p2,encoding='utf-8'):
        m=re.match(r'\[(\w+)',line)
        if m: cur=m.group(1); continue
        if cur and line.startswith('Evolutions') and line.split('=',1)[1].strip(): evo.add(cur)
with open(out,'a',encoding='utf-8') as o:
    o.write('namespace Rimketmon.Engine { public static partial class ItemData { public static readonly HashSet<string> CanEvolve = new HashSet<string>{ ' + ','.join('"%s"'%e for e in sorted(evo) if e in KNOWN) + ' }; } }\n')
print(len(evo),'evolving species')
print(len(rows), 'items;', sum(1 for r in rows if not r[2]), 'without ko name;', sum(1 for r in rows if r[8]), 'berries')
